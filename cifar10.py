def evaluationLoop(modelToTest, testingData, lossFunc, BATCH_SIZE, preprocessing):
    testDataLoader = torch.utils.data.DataLoader(testingData, batch_size = BATCH_SIZE, shuffle = True)
    modelToTest.eval()

    allPreds = torch.Tensor([]).to(device)
    allAnswers = torch.Tensor([]).to(device)
    for batch_inputs, actualLabels in iter(testDataLoader):
        batch_inputs = batch_inputs.to(device)
        actualLabels = actualLabels.to(device)

        preprocessed_batch_inputs = preprocessing (batch_inputs)
        predictions = modelToTest.forward(preprocessed_batch_inputs)
        predicted_classes = predictions.argmax(dim=1)
        currentLoss = lossFunc(predictions, actualLabels)

        allPreds = torch.cat([allPreds, predicted_classes])
        allAnswers = torch.cat([allAnswers, actualLabels])

    modelToTest.train()
    return (allPreds,
            allAnswers,
           )

def trainingLoop(modelToTrain, trainingData, lossFunc, myOptimizer, EPOCHS, BATCH_SIZE, preprocessing, testingData = None):
    trainDataLoader = torch.utils.data.DataLoader(trainingData, batch_size = BATCH_SIZE, shuffle = True)

    modelToTrain.train()
    losses = []
    test_accuracies = []

    total_batches_per_epoch = round(len(trainingData) / BATCH_SIZE)
    for current_epoch_num in range(EPOCHS):
        loss_for_epoch = 0
        for num, (batch_inputs, actualLabels) in enumerate(iter(trainDataLoader)):
            batch_inputs = batch_inputs.to(device)
            actualLabels = actualLabels.to(device)
            preprocessed_batch_inputs = preprocessing(batch_inputs)
            predictions = modelToTrain.forward(preprocessed_batch_inputs)
            currentLoss = lossFunc(predictions, actualLabels)
            currentLoss.backward()
            myOptimizer.step()
            myOptimizer.zero_grad()

            if (num%100 == 99):
              print("       Batch {}/{}".format(num+1, total_batches_per_epoch))
            loss_for_epoch += currentLoss.item()
        losses.append(loss_for_epoch/len(trainDataLoader))
        if testingData is not None:
            val_stats = evaluationLoop(modelToTrain, testingData, lossFunc, BATCH_SIZE, preprocessing)
            val_accuracy = (val_stats[0] == val_stats[1]).sum().item() / len(val_stats[1])
            print("Validation Stats: {:.2f}%".format(100*val_accuracy))
            test_accuracies.append(val_accuracy)
        print("Done with {} epochs; Average loss: {}".format(current_epoch_num+1, losses[-1]))

    return losses

